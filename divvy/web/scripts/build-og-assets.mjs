// Regenerates the link-preview card assets from og/card.js:
//   - og/fonts.js        Space Mono as base64 (the worker can't read files)
//   - public/og-card.png the static fallback card
// Run after changing the card design or the fonts: node scripts/build-og-assets.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';
import { buildCardSvg } from '../og/card.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fontDir = join(root, 'og', 'fonts');
const regular = readFileSync(join(fontDir, 'SpaceMono-Regular.ttf'));
const bold = readFileSync(join(fontDir, 'SpaceMono-Bold.ttf'));

writeFileSync(
  join(root, 'og', 'fonts.js'),
  `// Generated by scripts/build-og-assets.mjs — do not edit.
// Space Mono (og/fonts/, SIL OFL 1.1) base64-encoded for the og worker.

const decode = (b64) => Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));

export const fontBuffers = [
  decode('${regular.toString('base64')}'),
  decode('${bold.toString('base64')}'),
];
`,
);

const resvg = new Resvg(buildCardSvg(), {
  fitTo: { mode: 'width', value: 1200 },
  font: {
    fontFiles: [join(fontDir, 'SpaceMono-Regular.ttf'), join(fontDir, 'SpaceMono-Bold.ttf')],
    loadSystemFonts: false,
    defaultFontFamily: 'Space Mono',
  },
});
writeFileSync(join(root, 'public', 'og-card.png'), resvg.render().asPng());
console.log('wrote og/fonts.js and public/og-card.png');
